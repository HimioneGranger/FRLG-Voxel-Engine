function M.supports(text)
 if type(text)~='string' or text=='' then return false end
 for i=1,#text do if not patterns[text:sub(i,i)] then return false end end
 return true
end
function M.new(size)
 local scale=math.max(1,math.floor(size/7))
 local glyphs=" ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?-/:()'&"
 local width=5*scale;local height=7*scale
 local data=love.image.newImageData(1+#glyphs*(width+1),height)
 for i=0,#glyphs do for y=0,height-1 do data:setPixel(i*(width+1),y,1,0,1,1) end end
 for i=1,#glyphs do
  local rows=assert(patterns[glyphs:sub(i,i)])
  for y=0,height-1 do for x=0,width-1 do
   if rows[math.floor(y/scale)+1]:sub(math.floor(x/scale)+1,math.floor(x/scale)+1)=='1' then
    data:setPixel(1+(i-1)*(width+1)+x,y,1,1,1,1)
   end
  end end
 end
 local font=love.graphics.newImageFont(data,glyphs,scale)
 font:setFilter('nearest','nearest');data:release();return font
end
return M
