function G.normalize(key) return styles[key] and key or "patchwork" end
-- Sample original CPU texels, never the non-ground blade donor used by the
-- legacy raised base. ctx.groundKeys is version-native (Emerald or FireRed).
function G.nativeColor(ctx,cell,mid)
 if not ctx then return nil end
 local atlas=ctx.atlas or {};local keys=ctx.groundKeys or {}
 local function texels(id)
  if not id then return nil end
  if type(ctx.texels)=='function' then return ctx:texels(id) end
  if type(atlas.texels)=='function' then
   local ok,p=pcall(atlas.texels,id,'under');if ok and type(p)=='table' then return p end
  end
 end
 local function counts(p,onlyKeys)
  local c={};if p then for i=1,256 do local v=p[i]
   if type(v)=='number' and v>=0 and (not onlyKeys or keys[v]) then c[v]=(c[v] or 0)+1 end
  end end;return c
 end
 local function mode(c)
  local value,n=nil,0
  for v,k in pairs(c)do if k>n or(k==n and(value==nil or v<value))then value,n=v,k end end
  return value
 end
 mid=(cell and cell.groundMid) or mid or(cell and cell.mid)
 local original=texels(mid)
 local all=counts(original,false);local source=counts(original,true);local chosen=mode(source)
 -- nearMid is the native mesher's ground donor. Accept it only when its
 -- modal color is an actual background key present in this original tile;
 -- adjacent sand/path cannot change a green patch's hue.
 local near=cell and cell.nearMid
 if near and near~=mid then
  local neighbor=mode(counts(texels(near),false))
  if neighbor and keys[neighbor] and source[neighbor] then return neighbor end
  -- Ash/special palettes may have no ordinary green keys. A matching native
  -- donor is valid only when its modal RGB also occurs in the original tile.
  if not chosen and neighbor and all[neighbor] then return neighbor end
 end
 if chosen then return chosen end
 -- Original tile border is usually uncovered ground, including gray ash.
 -- Sample all four edges before resorting to the original full-tile mode.
 local edge={}
 if original then for i=1,256 do local x,z=(i-1)%16,math.floor((i-1)/16);local v=original[i]
  if (x==0 or x==15 or z==0 or z==15) and type(v)=='number' and v>=0 then edge[v]=(edge[v] or 0)+1 end
 end end
 chosen=mode(edge) or mode(all)
 if chosen then return chosen end
 -- Only absent CPU art takes this explicitly native-palette fallback. Never
 -- use the authored preview turf palette to guess a world background.
 if type(ctx.nativeGroundColor)=='number' then return ctx.nativeGroundColor end
 local native={};for v,on in pairs(keys)do if on and type(v)=='number' then native[v]=1 end end
 return mode(native)

end
function G.get(key,color)
 local s=styles[G.normalize(key)]
 s.textures=s.textures or {};local cacheKey=color or 'art-unavailable'
 if not s.textures[cacheKey] then
  local t={width=s.size,height=s.size,span=G.span,rgba={}}
  local palette=s.palette
  if type(color)=='number' then
   palette={};local r=math.floor(color/65536)%256;local g=math.floor(color/256)%256;local b=color%256
   local base={77,147,108};local native={r,g,b}
   for i,p in ipairs(s.palette)do local q={};for j=1,3 do q[j]=math.max(0,math.min(255,native[j]+p[j]-base[j]))end;q[4]=p[4];palette[i]=q end
  end
  for digit in s.pixels:gmatch('%d')do
   local p=palette[tonumber(digit)+1];for i=1,4 do t.rgba[#t.rgba+1]=p[i]end
  end
  s.textures[cacheKey]=t
 end
 return s.textures[cacheKey]
end
